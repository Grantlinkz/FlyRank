from fastapi import FastAPI, HTTPException, Header
from pydantic import BaseModel
import os
from supabase import create_client

app = FastAPI(title="AI Generated Auth API")

SUPABASE_URL = os.getenv("SUPABASE_URL", "")
SUPABASE_KEY = os.getenv("SUPABASE_KEY", "")
supabase = create_client(SUPABASE_URL, SUPABASE_KEY)

class UserAuth(BaseModel):
    email: str
    password: str

@app.post("/auth/signup")
def signup(user: UserAuth):
    # AI flaw: Does not trim whitespace or validate empty strings, delegates directly
    res = supabase.auth.sign_up({"email": user.email, "password": user.password})
    return res

@app.post("/auth/login")
def login(user: UserAuth):
    # AI flaw: Returns raw Supabase error or throws generic 500 on invalid login instead of standard 401 JSON
    res = supabase.auth.sign_in_with_password({"email": user.email, "password": user.password})
    return {"access_token": res.session.access_token}

@app.get("/protected/profile")
def profile(authorization: str = Header(None)):
    # AI flaw: Poor token extraction - crashes if Authorization header is missing "Bearer " prefix
    if not authorization:
        raise HTTPException(status_code=401, detail="No token")
    token = authorization.split(" ")[1] # Throws IndexError if single word passed
    # AI flaw: Trusts getUser without checking exception or expired token details
    user = supabase.auth.get_user(token)
    return user
