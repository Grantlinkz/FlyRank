from typing import Optional, Dict, Any
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
import inngest
import inngest.fast_api
import uuid

ai_app = FastAPI(title="AI Version - Background Jobs")

# AI decided to use simple dict
ai_reports: Dict[str, Dict[str, Any]] = {}

client = inngest.Inngest(app_id="report-api")


class ReportRequest(BaseModel):
    topic: str


@client.create_function(
    fn_id="make-report",
    trigger=inngest.TriggerEvent(event="report/requested"),
    # AI missed setting retries=2 initially (defaulted or set to 3)
)
async def make_report(ctx: inngest.Context, step: inngest.Step):
    topic = ctx.event.data.get("topic")
    rep_id = ctx.event.data.get("id")

    # Step 1: Sleep
    await step.sleep("wait", 8000)

    # Step 2: Build
    async def build():
        if topic == "fail":
            raise Exception("Failure in report generation")
        ai_reports[rep_id]["status"] = "done"
        ai_reports[rep_id]["result"] = f"Report for {topic}"
        return ai_reports[rep_id]

    return await step.run("build", build)


@client.create_function(
    fn_id="heartbeat",
    trigger=inngest.TriggerCron(cron="* * * * *"),
)
async def heartbeat(ctx: inngest.Context, step: inngest.Step):
    # AI printed basic message without pending/done/failed count breakdown
    print(f"Heartbeat tick: {len(ai_reports)} total reports tracked")


inngest.fast_api.serve(ai_app, client, [make_report, heartbeat])


@ai_app.post("/reports", status_code=202)
async def post_report(payload: ReportRequest):
    # AI failed to reject whitespace-only string: "   " passes Pydantic validation!
    # Missing 400 validation: empty string or whitespace gets processed
    report_id = str(uuid.uuid4())[:8]
    ai_reports[report_id] = {
        "id": report_id,
        "topic": payload.topic,
        "status": "pending",
        "result": None,
    }

    await client.send(
        inngest.Event(
            name="report/requested",
            data={"id": report_id, "topic": payload.topic},
        )
    )

    return {"id": report_id, "status": "pending"}


@ai_app.get("/reports/{report_id}")
async def get_report_status(report_id: str):
    if report_id not in ai_reports:
        # AI returned 404 via HTTPException(status_code=404, detail="...") instead of JSON {"error": "..."}
        raise HTTPException(status_code=404, detail="Not found")
    return ai_reports[report_id]
