import os
import sqlite3
from datetime import datetime
from pathlib import Path
from typing import Optional
from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse, FileResponse
from pydantic import BaseModel
from playwright.async_api import async_playwright

ai_reports_app = FastAPI(title="AI Version - PDF Report Generator")

DB_FILE = "ai_report.db"
REPORTS_STORAGE = Path("ai_reports_storage")
REPORTS_STORAGE.mkdir(parents=True, exist_ok=True)


class GenerateRequest(BaseModel):
    force: Optional[bool] = False


def get_db():
    conn = sqlite3.connect(DB_FILE)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS books (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT,
                price REAL,
                rating INTEGER,
                url TEXT
            );
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS reports (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                path TEXT,
                created_at TEXT
            );
        """)
        conn.commit()


init_db()


def get_aggregates():
    with get_db() as conn:
        cur = conn.cursor()
        total = cur.execute("SELECT COUNT(*) FROM books").fetchone()[0]
        avg_price = cur.execute("SELECT AVG(price) FROM books").fetchone()[0] or 0.0
        top5 = cur.execute("SELECT title, price, rating FROM books ORDER BY price DESC LIMIT 5").fetchall()
        ratings = cur.execute("SELECT rating, COUNT(*) FROM books GROUP BY rating").fetchall()
        all_books = cur.execute("SELECT title, price, rating FROM books").fetchall()
        return {
            "total": total,
            "avg_price": round(avg_price, 2),
            "top5": [dict(r) for r in top5],
            "ratings": [{"rating": r[0], "count": r[1]} for r in ratings],
            "all_books": [dict(r) for r in all_books],
        }


def build_html(data):
    # Notice: AI used basic CSS without defensive print rules (missing tr { break-inside: avoid; })
    top5_rows = "".join([f"<tr><td>{b['title']}</td><td>£{b['price']}</td><td>{b['rating']}</td></tr>" for b in data['top5']])
    all_rows = "".join([f"<tr><td>{b['title']}</td><td>£{b['price']}</td><td>{b['rating']}</td></tr>" for b in data['all_books']])
    
    return f"""
    <html>
    <head>
        <style>
            body {{ font-family: Arial, sans-serif; margin: 20px; }}
            table {{ width: 100%; border-collapse: collapse; margin-top: 15px; }}
            th, td {{ border: 1px solid #ccc; padding: 8px; text-align: left; }}
            th {{ background: #eee; }}
        </style>
    </head>
    <body>
        <h1>Catalog Report</h1>
        <p>Total Books: {data['total']}</p>
        <p>Average Price: £{data['avg_price']}</p>
        
        <h2>Top 5 Titles</h2>
        <table><thead><tr><th>Title</th><th>Price</th><th>Rating</th></tr></thead><tbody>{top5_rows}</tbody></table>
        
        <h2>All Books</h2>
        <table><thead><tr><th>Title</th><th>Price</th><th>Rating</th></tr></thead><tbody>{all_rows}</tbody></table>
    </body>
    </html>
    """


async def render_pdf_file(html: str, dest: Path):
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        page = await browser.new_page()
        await page.set_content(html)
        await page.pdf(path=str(dest), format="A4", print_background=True)
        await browser.close()


@ai_reports_app.post("/reports")
async def generate_report(req: Optional[GenerateRequest] = None):
    force = req.force if req else False

    # Check today's report
    if not force:
        with get_db() as conn:
            cur = conn.cursor()
            cur.execute("SELECT id, path FROM reports WHERE DATE(created_at) = DATE('now') ORDER BY id DESC LIMIT 1")
            existing = cur.fetchone()
            if existing:
                return JSONResponse(status_code=200, content={"id": existing["id"], "file": f"/reports/{existing['id']}/file"})

    # Create new report
    data = get_aggregates()
    html = build_html(data)
    
    with get_db() as conn:
        cur = conn.cursor()
        now = datetime.now().isoformat()
        cur.execute("INSERT INTO reports (path, created_at) VALUES (?, ?)", ("", now))
        rep_id = cur.lastrowid
        pdf_path = REPORTS_STORAGE / f"{rep_id}.pdf"
        cur.execute("UPDATE reports SET path = ? WHERE id = ?", (str(pdf_path), rep_id))
        conn.commit()

    await render_pdf_file(html, pdf_path)
    return JSONResponse(status_code=201, content={"id": rep_id, "file": f"/reports/{rep_id}/file"})


@ai_reports_app.get("/reports/{id}")
def get_report(id: int):
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute("SELECT id, path, created_at FROM reports WHERE id = ?", (id,))
        row = cur.fetchone()
        if not row:
            raise HTTPException(status_code=404, detail="Report not found")
        return {"id": row["id"], "created_at": row["created_at"], "file": f"/reports/{row['id']}/file"}


@ai_reports_app.get("/reports/{id}/file")
def get_file(id: int):
    with get_db() as conn:
        cur = conn.cursor()
        cur.execute("SELECT path FROM reports WHERE id = ?", (id,))
        row = cur.fetchone()
        if not row:
            raise HTTPException(status_code=404, detail="Report not found")
        path = Path(row["path"])
        if not path.exists():
            raise HTTPException(status_code=404, detail="PDF file not found")
        return FileResponse(path=str(path), media_type="application/pdf", filename=f"report-{id}.pdf")
